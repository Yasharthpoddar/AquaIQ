import csv
from datetime import datetime, timezone
import gzip
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
BASE='6660e24d356cfc5794b9fb0bffad0bc050ade217'
TEMP_PREFIX='reports/end_to_end_verification_20261022/checks_20261023/pytest_tmp/'
ACCURACY='reports/accuracy_experiments_20261027/'
PRIVATE={'.db','.sqlite','.sqlite3','.dump','.pem','.key','.pfx'}


def sha(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()


def write(name,obj):
    p=HERE/name
    if p.exists():raise FileExistsError('Use a fresh receipt.')
    p.write_text(json.dumps(obj,indent=2)+'\n',encoding='utf-8')


def git(*args):return subprocess.check_output(['git',*args],cwd=ROOT)


def private(p):
    return (p.name.startswith('.env') and p.name!='.env.example') or p.suffix.lower() in PRIVATE or any(w in p.name.lower() for w in ['licence','license','credentials','secrets'])


def walk(base):
    for current,dirs,files in os.walk(base,followlinks=False):
        parent=Path(current)
        dirs[:]=[n for n in dirs if n not in ['.git','venv','.venv','node_modules','.agents','.codex','.aws']
                 and not (parent/n).is_symlink() and not (parent/n).is_junction()]
        if 'pyvenv.cfg' in files:dirs[:]=[];continue
        for n in files:
            p=parent/n
            if not p.is_symlink() and not p.is_junction():yield p


def tree_hash(files):
    h=hashlib.sha256()
    for name,digest in sorted(files.items()):h.update((name+'\0'+digest+'\n').encode())
    return h.hexdigest()


def classify(name):
    if name.startswith(('tests/','dashboard/tests/','.github/')):return 'KEEP — required verification'
    if name.startswith(('reports/','docs/phase2_eval/','Mini_Project__Report_Overleaf_Template/')):return 'KEEP — authoritative evidence'
    return 'KEEP — essential'


def plan():
    tracked=[n for n in git('ls-files','-z').decode().split('\0') if n]
    proposed={};archives=[];review=[]
    drafts=['REPORT_analysis_v1_SUPERSEDED.md','REPORT_analysis_v2.md','REPORT_analysis_v2_initial.md','REPORT_analysis_v2_pre_final.md']
    duplicates={ACCURACY+'analysis_v1/'+n:ACCURACY+'analysis_v2/'+n for n in
                ['development_comparison.png','historical_diagnostics.png','figure_checksums.json']}
    duplicates[ACCURACY+'run_v2/progress.json']=ACCURACY+'run_v2/results.json'
    for name in tracked:
        if name.startswith(TEMP_PREFIX):proposed[name]=('ARCHIVE OR REMOVE','Captured pytest payload; generated by retained tests, no application/test/CI input reference.')
    for name in drafts:proposed[ACCURACY+name]=('CONSOLIDATE','Superseded Markdown draft; authoritative REPORT.md and corrected analysis_v2 retain the conclusions.')
    for name,canonical in duplicates.items():
        assert sha(ROOT/name)==sha(ROOT/canonical)
        proposed[name]=('CONSOLIDATE','Byte-identical copy of '+canonical)
    for name in list(proposed):
        data=git('show',BASE+':'+name);working=(ROOT/name).read_bytes()
        transform='raw' if data==working else 'crlf' if data.replace(b'\n',b'\r\n')==working and b'\r\n' not in data else None
        if transform is None:
            review.append({'path':name,'reason':'Git bytes do not recover the current bytes under a known newline transform.'});del proposed[name];continue
        archives.append({'path':name,'commit':BASE,'sha256':hashlib.sha256(working).hexdigest(),
                         'git_sha256':hashlib.sha256(data).hexdigest(),'transform':transform,
                         'reason':proposed[name][1], 'canonical_copy':duplicates.get(name)})
    old=json.loads((ROOT/'reports/repository_cleanup_20261027/initial/plan.json').read_text(encoding='utf-8'))
    roots=[ROOT/x['path'] for x in old['unresolved'] if x['path'].startswith('scratch/pytest-')]
    for directory in roots:
        children=list(directory.iterdir())
        if any(not p.name.startswith(('test_','nationwide','.lock')) for p in children):
            review.append({'path':directory.relative_to(ROOT).as_posix(),'reason':'Unexpected child; preserve entire location.'});continue
        for p in walk(directory):
            if private(p):review.append({'path':p.relative_to(ROOT).as_posix(),'reason':'Private/configuration/licence name; keep.'});continue
            proposed[p.relative_to(ROOT).as_posix()]=('DELETE — disposable','Generated pytest payload; references are historical file/preservation inventories, not runtime or scientific inputs.')
    for x in old['unresolved']:
        directory=ROOT/x['path']
        if directory.name!='__pycache__':continue
        for p in walk(directory):
            source=p.parent.parent/(p.name.split('.cpython-')[0].split('.pypy')[0]+'.py')
            if p.suffix in ['.pyc','.pyo'] and source.is_file():proposed[p.relative_to(ROOT).as_posix()]=('DELETE — disposable','Bytecode with retained Python source; regenerated by interpreter.')
            else:review.append({'path':p.relative_to(ROOT).as_posix(),'reason':'No unambiguous source counterpart; preserve.'})
    entries=[]
    for name,(category,reason) in sorted(proposed.items()):
        p=ROOT/name
        assert not private(p) and p.resolve().is_relative_to(ROOT) and not p.is_symlink() and not p.is_junction()
        s=p.stat();entries.append({'path':name,'category':category,'reason':reason,'tracked':name in tracked,
                                  'bytes':s.st_size,'mtime_ns':s.st_mtime_ns,'sha256':sha(p)})
    with gzip.open(HERE/'deletions.json.gz','wt',encoding='utf-8') as f:json.dump(entries,f,separators=(',',':'))
    write('archives.json',{'version':1,'source_commit':BASE,'files':archives})
    write('review.json',review)
    fields=['path','classification','git_status','bytes','mtime_utc','sha256','reason']
    with gzip.open(HERE/'inventory.csv.gz','wt',encoding='utf-8',newline='') as f:
        out=csv.DictWriter(f,fieldnames=fields);out.writeheader()
        for name in sorted(set(tracked)|set(proposed)):
            p=ROOT/name
            if private(p):continue
            s=p.stat();category,reason=proposed.get(name,(classify(name),'Retained source, configuration, test, academic deliverable or evidence; no proven disposable role.'))
            out.writerow({'path':name,'classification':category,'git_status':'tracked' if name in tracked else 'ignored',
                          'bytes':s.st_size,'mtime_utc':datetime.fromtimestamp(s.st_mtime,timezone.utc).isoformat(),
                          'sha256':sha(p),'reason':reason})
    # Protect data, model/rollback assets and all application/test/configuration
    # inputs. Read private configuration only by presence, never by content.
    protected={};presence=[]
    bases=['api','db','models','data','data_ingestion','preprocessing','tests','dashboard','research','deploy',
           'scratch/retraining_20261027/rollback','Mini_Project__Report_Overleaf_Template']
    for base in bases:
        for p in walk(ROOT/base):
            name=p.relative_to(ROOT).as_posix()
            if name in proposed:continue
            if private(p):presence.append(name);continue
            protected[name]=sha(p)
    for name in ['config.yaml','.env.example','requirements.txt','requirements-download.txt','requirements-tracking.txt','setup.ps1','setup.sh','api_spec.md']:
        protected[name]=sha(ROOT/name)
    for folder in ['reports/final_release_20261026','reports/retraining_20261027','reports/accuracy_experiments_20261027']:
        for p in walk(ROOT/folder):
            name=p.relative_to(ROOT).as_posix()
            if name not in proposed and not private(p):protected[name]=sha(p)
    # The full local seal stays ignored; the compact tree digest is committed.
    seal=ROOT/'scratch/repository_simplification_20261027';seal.mkdir(exist_ok=False)
    (seal/'protected.json').write_text(json.dumps(protected),encoding='utf-8')
    write('baseline.json',{'branch':'main','head':BASE,'status':'## main...origin/main\n','remote':'https://github.com/Yasharthpoddar/AquaIQ.git',
          'tracked_files':len(tracked),'tracked_logical_bytes':sum((ROOT/n).stat().st_size for n in tracked),
          'tracked_deletion_files':len(archives),'total_deletion_files':len(entries),'deletion_logical_bytes':sum(e['bytes'] for e in entries),
          'deletion_manifest_sha256':sha(HERE/'deletions.json.gz'),'protected_files':len(protected),
          'protected_tree_sha256':tree_hash(protected),'private_files_presence_only':presence+(['.env'] if (ROOT/'.env').is_file() else []),
          'historical_builds':'KEEP/REVIEW: process inspection unavailable (CimException); existing build/runtime outputs not touched.',
          'created_at_utc':datetime.now(timezone.utc).isoformat()})
    summary=['# Proposed removals — reviewed before deletion','',
             'Tracked captures are recoverable byte-for-byte from Git '+BASE+'. Runtime builds, dependencies, source observations and tests stay in place.','',
             '| Group | Files | Logical bytes | Evidence / recovery |','| --- | ---: | ---: | --- |']
    for label,predicate in [('Captured pytest payload',lambda e:e['path'].startswith(TEMP_PREFIX)),('Accuracy drafts / duplicates',lambda e:e['path'].startswith(ACCURACY)),
                            ('Ignored generated test payload',lambda e:e['path'].startswith('scratch/pytest-')),('Source-backed bytecode',lambda e:e['path'].endswith(('.pyc','.pyo')) and not e['path'].startswith('scratch/pytest-'))]:
        group=[e for e in entries if predicate(e)];summary.append(f"| {label} | {len(group)} | {sum(e['bytes'] for e in group):,} | Retained test generators or archived Git bytes; manifests and outcomes kept. |")
    (HERE/'PROPOSED.md').write_text('\n'.join(summary)+'\n',encoding='utf-8')
    print((HERE/'baseline.json').read_text(encoding='utf-8'),flush=True)


def apply():
    baseline=json.loads((HERE/'baseline.json').read_text());assert sha(HERE/'deletions.json.gz')==baseline['deletion_manifest_sha256']
    with gzip.open(HERE/'deletions.json.gz','rt',encoding='utf-8') as f:entries=json.load(f)
    # Preflight every exact target before deleting anything. Candidate ancestor
    # paths are checked once per directory; never traverse a reparse point.
    checked=set()
    for e in entries:
        p=ROOT/e['path'];assert p.is_relative_to(ROOT) and not private(p)
        for q in [p,*p.parents]:
            if q==ROOT.parent or q in checked:break
            assert not q.is_symlink() and not q.is_junction();checked.add(q)
        s=p.stat();assert s.st_size==e['bytes'] and s.st_mtime_ns==e['mtime_ns'] and sha(p)==e['sha256'],e['path']
    free=shutil.disk_usage(ROOT).free;parents=set()
    for e in entries:
        p=ROOT/e['path'];p.unlink();parents.add(p.parent)
    removed_dirs=0
    for p in sorted(parents,key=lambda x:len(x.parts),reverse=True):
        while p!=ROOT and p.is_relative_to(ROOT):
            try:p.rmdir();removed_dirs+=1
            except OSError:break
            p=p.parent
    write('applied.json',{'removed_files':len(entries),'removed_empty_directories':removed_dirs,
          'logical_bytes_removed':sum(e['bytes'] for e in entries),'disk_free_before':free,'disk_free_after':shutil.disk_usage(ROOT).free,
          'tracked_files_removed':sum(e['tracked'] for e in entries),'no_recursive_parent_deletion':True})
    print((HERE/'applied.json').read_text(),flush=True)


def verify():
    before=json.loads((ROOT/'scratch/repository_simplification_20261027/protected.json').read_text(encoding='utf-8'))
    failures=[n for n,h in before.items() if not (ROOT/n).is_file() or sha(ROOT/n)!=h]
    write('preservation.json',{'protected_files':len(before),'protected_tree_sha256':tree_hash(before),'changed_or_missing':failures,'passed':not failures})
    assert not failures,failures
    print('All protected source, data, model and scientific result bytes unchanged.',flush=True)


if __name__=='__main__':
    {'plan':plan,'apply':apply,'verify':verify}[sys.argv[1]]()
